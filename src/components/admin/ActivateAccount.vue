<template>
	<el-form ref="formRef" :model="form" :rules="rules" label-position="top" size="large" @submit.prevent="save">
		<span class="page-eyebrow">First sign-in</span>
		<h2>Choose your password</h2>
		<p>This account was created with a default password generated by the system. It stays switched off until you replace that password.</p>
		<el-form-item label="New password" prop="password">
			<el-input v-model="form.password" type="password" show-password autocomplete="new-password" />
		</el-form-item>
		<el-form-item label="Confirm password" prop="confirm">
			<el-input v-model="form.confirm" type="password" show-password autocomplete="new-password" />
		</el-form-item>
		<el-button type="primary" native-type="submit" class="w-100" :loading="saving">Activate account</el-button>
	</el-form>
</template>

<script setup>
import { reactive, ref } from "vue";
import { ElMessage } from "element-plus";
import { adminApi } from "@/services/adminService";
import { useAuthStore } from "@/store/authStore";

const emit = defineEmits(["done"]);
const authStore = useAuthStore();
const formRef = ref(null);
const saving = ref(false);
const form = reactive({ password: "", confirm: "" });

const rules = {
	password: [
		{
			validator: (_rule, value, callback) => {
				if (!value || value.length < 12) return callback(new Error("Use at least 12 characters"));
				return callback();
			},
			trigger: "blur",
		},
	],
	confirm: [
		{
			validator: (_rule, value, callback) =>
				value !== form.password ? callback(new Error("Passwords do not match")) : callback(),
			trigger: "blur",
		},
	],
};

const save = async () => {
	const valid = await formRef.value.validate().catch(() => false);
	if (!valid || !authStore.adminId) return;
	saving.value = true;
	try {
		await adminApi.admins.update(authStore.adminId, { password: form.password });
		authStore.logout();
		ElMessage.success("Password saved. The account is active. Sign in with the new password.");
		emit("done");
	} catch (error) {
		ElMessage.error(error?.message || "The password could not be saved.");
	} finally {
		saving.value = false;
	}
};
</script>

